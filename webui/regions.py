_CITY_TO_PROVINCE = {
    city: pcode for pcode, item in PROVINCES.items() for city, _ in item["cities"]
}
_NAMES = {pcode: item["name"] for pcode, item in PROVINCES.items()}
_NAMES.update({city: name for item in PROVINCES.values() for city, name in item["cities"]})


def normalize_area(code) -> str:
    """把任意输入收敛成合法地区码，非法值一律返回空串（调用方据此走直连）。"""
    text = str(code or "").strip()
    if not text or text == ALL_AREA:
        return ""
    return text if text in _NAMES else ""


def area_label(code) -> str:
    """给界面和日志用的可读名字，例如「河北省 · 石家庄市」。"""
    text = normalize_area(code)
    if not text:
        return ""
    pcode = _CITY_TO_PROVINCE.get(text)
    if not pcode:
        return _NAMES[text]
    return f"{_NAMES[pcode]} · {_NAMES[text]}"


def region_tree() -> list[dict]:
    """给前端省市两级下拉用的结构。"""
    return [
        {
            "code": pcode,
            "name": item["name"],
            "cities": [{"code": code, "name": name} for code, name in item["cities"]],
        }
        for pcode, item in sorted(PROVINCES.items())
    ]
